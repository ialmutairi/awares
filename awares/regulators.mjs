/** كل النطاقات المقبولة كمصدر رسمي — تُستخدم في التحقق من الروابط */
export const OFFICIAL_HOSTS = new Set([
  ...PRIMARY_SOURCES.flatMap((s) => [s.host, s.deepHost].filter(Boolean)),
  ...REGULATORS.flatMap((r) => [r.host, ...(r.alt || [])]),
]);

/** الجهات المنطبقة على قطاع، مع الجهات العامة الموسومة "*" */
export function regulatorsFor(sectorId) {
  return REGULATORS.filter((r) => r.sectors.includes(sectorId) || r.sectors.includes("*"));
}

export function regulatorByHost(host) {
  const h = String(host || "").toLowerCase().replace(/^www\./, "");
  return REGULATORS.find((r) => r.host === h || (r.alt || []).includes(h)) || null;
}

/** سطور مختصرة تُحقن في الصياغة — تمنع النموذج من اختراع جهة أو نطاق */
export function regulatorBrief(sectorIds = []) {
  const list = sectorIds.length
    ? [...new Set(sectorIds.flatMap((id) => regulatorsFor(id)))]
    : REGULATORS;
  return list.map((r) => `- ${r.name} (${r.acr}) — ${r.host} — ${r.scope}`).join("\n");
}
